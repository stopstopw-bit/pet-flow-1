/**
 * ตัดคำนำหน้าที่ติดมากับชื่อน้องตอนกรอก/ก๊อปข้อความ เช่น "ชื่อ โชคดี" / "ชื่อน้อง: โชคดี" → "โชคดี"
 * ตัดเฉพาะคำว่า "ชื่อ" ที่ตามด้วยเว้นวรรคหรือ ":" เท่านั้น — ชื่อจริงอย่าง "ชื่อเสียง" ไม่โดน
 * (เดิมเก็บไปทั้งก้อน ทำให้น้องตัวเดียวขึ้นสองรายการในประวัติรายตัว)
 */
export function cleanPetName(name?: string): string {
  const s = (name || "").trim();
  const cut = s.replace(/^ชื่อ(?:น้อง)?\s*[:：]\s*|^ชื่อ(?:น้อง)?\s+/, "").trim();
  return cut || s;
}
